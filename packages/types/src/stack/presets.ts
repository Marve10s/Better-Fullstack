export type PresetOptionSelection = Readonly<Partial<Record<PresetOptionId, string>>>;

export function resolvePresetId(id: string): PresetId | undefined {
  const target = (PRESET_ALIASES as Record<string, PresetId | undefined>)[id] ?? id;
  return PRESET_DEFINITIONS.find((preset) => preset.id === target)?.id;
}

export function getPreset(id: string): PresetDefinition | undefined {
  const resolved = resolvePresetId(id);
  return PRESET_DEFINITIONS.find((preset) => preset.id === resolved);
}

export function validatePresetOptions(
  preset: PresetDefinition,
  selection: PresetOptionSelection,
): string | null {
  for (const [optionId, choiceId] of Object.entries(selection) as [string, string | undefined][]) {
    if (choiceId === undefined) continue;
    const option = preset.options?.find((candidate) => candidate.id === optionId);
    if (!option) return `Preset '${preset.id}' has no '${optionId}' option.`;
    if (!option.choices.some((choice) => choice.id === choiceId)) {
      const valid = option.choices.map((choice) => choice.id).join(", ");
      return `Unknown ${optionId} '${choiceId}' for preset '${preset.id}'. Choose one of: ${valid}.`;
    }
  }
  return null;
}

export function applyPresetOptions(
  preset: PresetDefinition,
  selection: PresetOptionSelection = {},
): PresetStack {
  const error = validatePresetOptions(preset, selection);
  if (error) throw new Error(error);
  const stack: PresetStack = { ecosystem: getPresetEcosystem(preset), ...preset.stack };
  for (const option of preset.options ?? []) {
    const choice =
      option.choices.find((candidate) => candidate.id === selection[option.id]) ??
      option.choices[0];
    Object.assign(stack, choice.stack);
  }
  return stack;
}

export function getPresetEcosystem(preset: PresetDefinition) {
  return (
    PRESET_CATEGORIES.find((category) => category.id === preset.category)?.ecosystem ?? "typescript"
  );
}

export function getPresetVariants(preset: PresetDefinition): PresetOptionSelection[] {
  return (preset.options ?? []).reduce<PresetOptionSelection[]>(
    (variants, option) =>
      variants.flatMap((variant) =>
        option.choices.map((choice) => ({ ...variant, [option.id]: choice.id })),
      ),
    [{}],
  );
}
