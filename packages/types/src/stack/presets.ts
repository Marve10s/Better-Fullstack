const STARTER_TRACK_SELECTION_BY_PRESET = new Map<string, StackSelectionState>(
  STARTER_TRACK_DEFINITIONS.map((track) => [track.presetId, track.selection]),
);

function starterTrackSelection(presetId: string): StackSelectionState {
  const selection = STARTER_TRACK_SELECTION_BY_PRESET.get(presetId);
  if (!selection) throw new Error(`Missing starter track selection for preset '${presetId}'.`);
  return selection;
}

