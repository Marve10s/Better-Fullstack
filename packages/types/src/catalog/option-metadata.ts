export function getCategoryOrderForEcosystem(
  ecosystem: OptionCategoryEcosystem,
): readonly OptionCategory[] {
  switch (ecosystem) {
    case "react-native":
      return REACT_NATIVE_CATEGORY_ORDER;
    case "rust":
      return RUST_CATEGORY_ORDER;
    case "python":
      return PYTHON_CATEGORY_ORDER;
    case "go":
      return GO_CATEGORY_ORDER;
    case "crystal":
      return ["crystalWebFramework", "crystalOrm", "crystalAuth", "crystalTesting", "crystalValidation", "crystalCache", "crystalJobs", "aiDocs", "git", "install"];
    case "java":
      return JAVA_CATEGORY_ORDER;
    case "dotnet":
      return DOTNET_CATEGORY_ORDER;
    case "ruby":
      return RUBY_CATEGORY_ORDER;
    case "php":
      return PHP_CATEGORY_ORDER;
    case "elixir":
      return ELIXIR_CATEGORY_ORDER;
    case "typescript":
      return TYPESCRIPT_CATEGORY_ORDER;
  }
}

export function getCategoryDisplayName(categoryKey: string): string {
  const definition: CategoryDefinition | undefined =
    CATEGORY_DEFINITIONS[categoryKey as OptionCategory];
  if (definition?.displayName) return definition.displayName;

  const result = categoryKey.replace(/([A-Z])/g, " $1");
  return result.charAt(0).toUpperCase() + result.slice(1);
}

