import { makeConfig } from "@test/_fixtures/config-factory";
import { describe, expect, it } from "bun:test";

import type { VirtualNode } from "@/types";

import { generateVirtualProject } from "@/generator";
import { EMBEDDED_TEMPLATES } from "@/templates.generated";

function findFile(node: VirtualNode, path: string): string | undefined {
  if (node.type === "file") return node.path === path ? node.content : undefined;
  for (const child of node.children) {
    const content = findFile(child, path);
    if (content !== undefined) return content;
  }
  return undefined;
}

describe(".NET README", () => {
  it("keeps the ASP.NET Core README instead of the TypeScript one", async () => {
    const result = await generateVirtualProject({
      config: makeConfig({ ecosystem: "dotnet", dotnetWebFramework: "aspnet-minimal" }),
      templates: EMBEDDED_TEMPLATES,
    });

    const readme = result.tree ? findFile(result.tree.root, "README.md") : undefined;
    expect(readme).toContain("ASP.NET Core project generated by Better Fullstack");
    expect(readme).toContain("dotnet run");
    expect(readme).not.toContain("TypeScript");
  });

  it("points dotnet test at the generated test project", async () => {
    const result = await generateVirtualProject({
      config: makeConfig({
        ecosystem: "dotnet",
        projectName: "my-api",
        dotnetWebFramework: "aspnet-minimal",
        dotnetTesting: ["xunit"],
      }),
      templates: EMBEDDED_TEMPLATES,
    });

    const readme = result.tree ? findFile(result.tree.root, "README.md") : undefined;
    expect(readme).toContain("dotnet test my_api.Tests");
    expect(result.tree && findFile(result.tree.root, "my_api.Tests/my_api.Tests.csproj")).toBeDefined();
  });
});
